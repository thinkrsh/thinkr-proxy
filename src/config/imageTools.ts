// What the Image page may ask of each image model beyond its shape (the owner, 25 Oct 2026: the
// Image page with more tools). Read on 25 Oct 2026 from GET https://openrouter.ai/api/v1/images/models
// and GET https://openrouter.ai/api/v1/images/models/<slug>/endpoints:
// - Sizes: only a model of the Images API with one endpoint that prices each image by its size; each
//   size costs the price of its variant, the price without a variant goes with the smallest size,
//   and a size with no price is left out. A model priced by tokens or by megapixels gets no sizes,
//   since the cost of a size would be a guess; so does a model reached by a chat completion, which
//   takes no size.
// - Photos: the fewest and the most input references of the model, at most PHOTO_LIMIT, which
//   keeps four scaled photos inside the body limit of the proxy (SERVER.maxMediaBodyBytes). A photo
//   adds the input price of the model when it charges by the image; a model that charges for photos
//   by tokens adds a cent or less, which the charge on the reported cost covers. The models of
//   Recraft that charge for style images by the request carry that price in their cost.
// - Seed and a transparent background: models of the Images API whose every endpoint takes them.
// The shapes of each model are in config/models.ts.

/** One size that the user may pick, and what one image of that size costs at the provider. */
export interface ImageSize {
  /** A resolution of OpenRouter, such as '1K' or '4K'. */
  readonly resolution: string;
  readonly costUsd: number;
}

export interface ImageTools {
  /** The sizes that the user may pick, smallest first; empty when the model takes no size. */
  readonly sizes: readonly ImageSize[];
  /** The size of a request that picks none, which the proxy then leaves to the provider. */
  readonly defaultSize: string | null;
  /** The fewest photos of one request: one for a model that draws in the style of a photo. */
  readonly minPhotos: number;
  /** The most photos of one request: the image to change, or the images to combine. */
  readonly maxPhotos: number;
  /** What each photo adds at the provider, about. */
  readonly photoCostUsd: number;
  /** The model takes a seed, so the same prompt and seed give the same image again. */
  readonly seed: boolean;
  /** The model can leave the background transparent. */
  readonly transparent: boolean;
  /** The format to ask for with a transparent background, when the model takes one; else null. */
  readonly transparentFormat: 'png' | null;
}

