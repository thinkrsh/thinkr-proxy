import type {
  AudioMode,
  AudioUnit,
  ModelInfo,
  ModelPricing,
  SourcedMode,
  SourcedUnit,
} from '../contract.js';

/**
 * What the catalog knows of a model. The proxy adds the price, the tools that the user sees, and
 * whether the model always thinks (config/thinking.ts) or can search the web (config/webSearch.ts).
 */
export type CatalogInfo = Omit<
  ModelInfo,
  'pricing' | 'media' | 'audio' | 'sourced' | 'alwaysThinks' | 'thinksInFull' | 'webSearch'
>;

/**
 * How OpenRouter takes an image request: a chat completion, which can force zero data retention,
 * with what the model answers with (Gemini writes a line of text beside its image, others only
 * draw); or the Images API, which some models need ("cannot be used with the chat/completions
 * endpoint", FLUX 3, 23 Oct 2026) and which takes no data policy, so the level Open only.
 */
export type ImageApi =
  | { readonly name: 'chat'; readonly modalities: readonly ('image' | 'text')[] }
  | { readonly name: 'images' };

/** What the proxy asks of an image model, and what one image costs Thinkr, about. */
export interface ImageSettings {
  readonly kind: 'image';
  /** The shape of the image when the user picks none. */
  readonly aspectRatio: string;
  /**
   * The shapes that the user may pick (the owner, 25 Oct 2026): a wide, a square, and a tall
   * ratio among those the model takes, the default among them.
   */
  readonly aspectRatios: readonly string[];
  readonly api: ImageApi;
  /**
   * One image at the provider, about: the price that the app shows and the least a balance must
   * hold. A paid image costs the cost that OpenRouter reports, plus 25% (decision 52).
   */
  readonly costUsd: number;
}

/**
 * What the proxy asks of a video model (16:9, 720p, the shortest length, unless the user picks
 * another shape or length), and its cost, about.
 */
export interface VideoSettings {
  readonly kind: 'video';
  readonly aspectRatio: string;
  /** The shapes that the user may pick, as for an image. */
  readonly aspectRatios: readonly string[];
  readonly seconds: number;
  /**
   * The lengths that the user may pick, in seconds, shortest first (the owner, 25 Oct 2026): the
   * shortest, then those closest to 5, 10, and 15 seconds among the lengths the model takes.
   */
  readonly durations: readonly number[];
  readonly resolution: string;
  /** Sound with the video, for the models that make it. */
  readonly audio: boolean;
  /**
   * One video of `seconds` at the provider, about: plus 25%, what a balance pays ahead. A longer
   * video costs the same for each second. Once the job ends, the balance pays the cost that
   * OpenRouter reports, plus 25% (decision 52), and gets the rest back.
   */
  readonly costUsd: number;
}

/**
 * What the proxy asks of a model of audio (the owner, 26 Oct 2026), what it charges for, and what
 * one request costs Thinkr, about.
 */
export interface AudioSettings {
  readonly kind: 'audio';
  readonly mode: AudioMode;
  /**
   * How OpenRouter takes it: the speech API (openrouter.ai/docs/guides/overview/multimodal/tts.md),
   * or a chat completion whose stream carries the audio (Lyria, .../multimodal/audio.md).
   */
  readonly api: 'speech' | 'chat';
  /**
   * What the provider charges for each unit, in USD: each character read, each second made (Gemini
   * TTS charges its audio tokens, AUDIO.geminiTokensPerSecond a second), or each piece.
   */
  readonly rate: { readonly per: AudioUnit; readonly usd: number };
  /**
   * One request at the provider, about: a text of AUDIO.trialChars for a voice, about ten seconds
   * for a sound, one piece of music. The free trial takes the model while its price stays under
   * TRIAL.dearest.imageUsd. A paid request costs what its audio cost, plus 25% (decision 52).
   */
  readonly costUsd: number;
}

/**
 * What the proxy asks of a model of a sourced video (decision 216, 26 Oct 2026), what it charges
 * for, and what one video costs Thinkr, about. The sources and their limits are in
 * config/sourcedTools.ts.
 */
export interface SourcedSettings {
  readonly kind: 'sourcedVideo';
  readonly mode: SourcedMode;
  /**
   * What the provider charges for each unit, in USD: each second of the video it makes, or each
   * megapixel of each second of an upscale, precise (`usd`) or creative (`creativeUsd`).
   */
  readonly rate: {
    readonly per: SourcedUnit;
    readonly usd: number;
    readonly creativeUsd: number | null;
  };
  /** The least that one video costs, in USD; 0 when the provider charges no least. */
  readonly minUsd: number;
  /**
   * One video of 5 seconds at the defaults, about: what the catalog shows. A balance pays ahead
   * the estimate of its own source, plus 25%, and once the job ends, the cost that OpenRouter
   * reports, plus 25% (decision 52).
   */
  readonly costUsd: number;
}

export type MediaSettings = ImageSettings | VideoSettings | AudioSettings | SourcedSettings;

export interface CatalogModel {
  readonly info: CatalogInfo;
  /** The OpenRouter model slug. Null in the private lane, which never goes through OpenRouter. */
  readonly openRouterSlug: string | null;
  /** What the provider charges Thinkr for a million tokens. */
  readonly cost: ModelPricing | null;
  /**
   * The price of decision 134 for a million tokens: 25% under the priciest of Tinfoil and Venice
   * for a chat of 1,000 tokens in and 500 out, input and output apart, rounded down to the cent;
   * under both, and under the cost on most models, on purpose ("gpp rugi kita bakar uang dulu buat
   * narik user", decision 132). A paid chat costs its tokens at this price, whatever the provider
   * charged. Null: a paid chat costs what its answer cost, plus 25% (decision 52).
   */
  readonly price: ModelPricing | null;
  /** A model of images, video, or audio: what the proxy asks of it. Absent for a model of text. */
  readonly media?: MediaSettings;
}

